import SwiftUI

/// 圆角系统 - 全局统一使用
enum AppRadius {
    static let small: CGFloat = 8       // 按钮、小标签
    static let medium: CGFloat = 12     // 输入框、小卡片
    static let large: CGFloat = 16      // 主卡片、面板
    static let xlarge: CGFloat = 20     // 大容器
    static let pill: CGFloat = 999      // 胶囊按钮
}